// Apply data/ri_verified_coverage_2026/RI_VERIFIED_RULES_2026.json to the
// marketplace bundle (dist/marketplace/marketplace.js). dist/app.js is the
// separate homepage script and must not be touched.
//
// 1. Moves every legacy Rhode Island rule out of COVERAGE_RULES into
//    data/ri_verified_coverage_2026/QUARANTINED_UNSUPPORTED_RI_RULES.json.
//    None of them were backed by a real plan document.
// 2. Inserts the evidence-verified rules, benefits and plans as a generated
//    block between markers (re-running replaces the block).
//
// Usage: python3 scratch/build_ri_verified_rules.py && node scratch/apply_ri_verified_rules.js

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const BUNDLE = path.join(ROOT, 'dist/marketplace/marketplace.js');
const DATA_DIR = path.join(ROOT, 'data/ri_verified_coverage_2026');
const VERIFIED = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'RI_VERIFIED_RULES_2026.json'), 'utf8'));

const BLOCK_START = '  // --- RI VERIFIED COVERAGE (GENERATED by scratch/apply_ri_verified_rules.js - do not edit) ---';
const BLOCK_END = '  // --- END RI VERIFIED COVERAGE ---';

const LEGACY_RI_PLAN = /^(CMS:RI:|QHP:RI:|ri_|bcbsri_|neighborhood_|uhc_medicare_dual|tufts_ri|nhpri)/;
const isLegacyRiRule = (r) =>
  r.state === 'RI' || LEGACY_RI_PLAN.test(String(r.plan_id)) || String(r.canonical_plan_key || '').startsWith('CMS:RI:');

function loadBundleData(src) {
  const hook = "window.__BUNDLE_DATA__ = { PLANS, RI_OFFICIAL_SELECTOR_PLANS, COVERAGE_RULES, PRODUCTS, SERVICES, BENEFITS };\n  if (document.readyState === 'loading')";
  const window = {};
  const document = { readyState: 'loading', addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, getElementById() { return null; } };
  const localStorage = { getItem() {}, setItem() {}, removeItem() {} };
  const ctx = { window, document, localStorage, console, URLSearchParams };
  vm.createContext(ctx);
  vm.runInContext(src.replace("if (document.readyState === 'loading')", hook), ctx);
  return window.__BUNDLE_DATA__;
}

// Index of the "]" closing the array literal that opens at openIdx (string-aware).
function matchingBracket(src, openIdx) {
  let depth = 0;
  let quote = null;
  for (let i = openIdx; i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
    } else if (c === '"' || c === "'" || c === '`') quote = c;
    else if (c === '[') depth++;
    else if (c === ']' && --depth === 0) return i;
  }
  throw new Error('Unbalanced COVERAGE_RULES array');
}

let src = fs.readFileSync(BUNDLE, 'utf8');

// Drop a previously generated block so re-runs are idempotent.
const oldStart = src.indexOf(BLOCK_START);
if (oldStart !== -1) {
  const oldEnd = src.indexOf(BLOCK_END, oldStart) + BLOCK_END.length;
  src = src.slice(0, oldStart) + src.slice(oldEnd + 1);
}

const data = loadBundleData(src);
const present = data.COVERAGE_RULES.filter(Boolean); // also drops array holes
const quarantined = present.filter(isLegacyRiRule);
const kept = present.filter((r) => !isLegacyRiRule(r));

// Validate generated rules against the catalog and selector roster.
const targetIds = new Set([
  ...data.PRODUCTS.map((p) => p.id),
  ...data.SERVICES.map((s) => s.id || s.service_id),
  ...data.BENEFITS.map((b) => b.id || b.benefit_id),
  ...VERIFIED.benefits.map((b) => b.id),
]);
const planIds = new Set([...data.RI_OFFICIAL_SELECTOR_PLANS.map((p) => p.id), ...VERIFIED.plans.map((p) => p.id)]);
const problems = VERIFIED.rules.flatMap((r) => [
  ...(targetIds.has(r.target_id) ? [] : [`unknown target ${r.target_id} in ${r.rule_id}`]),
  ...(planIds.has(r.plan_id) ? [] : [`unknown plan ${r.plan_id} in ${r.rule_id}`]),
]);
if (problems.length) {
  console.error('APPLY FAILED:\n  ' + [...new Set(problems)].join('\n  '));
  process.exit(1);
}

// Rewrite the COVERAGE_RULES literal without the legacy RI rules.
const declIdx = src.indexOf('const COVERAGE_RULES = [');
const openIdx = src.indexOf('[', declIdx);
const closeIdx = matchingBracket(src, openIdx);
let tail = closeIdx + 1;
while (src[tail] === ';') tail++;
const rewritten = `const COVERAGE_RULES = ${JSON.stringify(kept, null, 2)};`;

const block = [
  BLOCK_START,
  `  // Built ${VERIFIED.generated} from data/ri_verified_coverage_2026/evidence_spec.json.`,
  '  // Every rule quotes its official source document; see RI_VERIFIED_RULES_AUDIT.csv.',
  `  const RI_VERIFIED_COVERAGE = ${JSON.stringify({ rules: VERIFIED.rules, benefits: VERIFIED.benefits, plans: VERIFIED.plans }, null, 2)};`,
  '  COVERAGE_RULES.push(...RI_VERIFIED_COVERAGE.rules);',
  '  BENEFITS.push(...RI_VERIFIED_COVERAGE.benefits);',
  '  RI_OFFICIAL_SELECTOR_PLANS.push(...RI_VERIFIED_COVERAGE.plans);',
  BLOCK_END,
].join('\n');

src = src.slice(0, declIdx) + rewritten + '\n\n' + block + '\n' + src.slice(tail);

// Re-load the patched source to prove it still evaluates.
const check = loadBundleData(src);
const expected = kept.length + VERIFIED.rules.length;
if (check.COVERAGE_RULES.length !== expected) {
  console.error(`APPLY FAILED: expected ${expected} rules after patch, found ${check.COVERAGE_RULES.length}`);
  process.exit(1);
}

if (quarantined.length) {
  const qPath = path.join(DATA_DIR, 'QUARANTINED_UNSUPPORTED_RI_RULES.json');
  const previous = fs.existsSync(qPath) ? JSON.parse(fs.readFileSync(qPath, 'utf8')).rules : [];
  fs.writeFileSync(qPath, JSON.stringify({
    reason: 'Removed from the marketplace: these Rhode Island rules were generated from product-name keywords or placeholder files, not from official plan documents.',
    removed_on: new Date().toISOString().slice(0, 10),
    rules: [...previous, ...quarantined],
  }, null, 2));
}

fs.writeFileSync(BUNDLE, src);

// Homepage lookup (Medicare and Medicaid cards): every RI Medicare and
// Medicaid plan in the selector with its evidence-backed listings, built from
// the same rules as the marketplace so both pages agree.
const VERIFIED_CARDS = path.join(ROOT, 'dist/ri_verified_cards.json');
const catalog = new Map([...check.PRODUCTS, ...check.SERVICES, ...check.BENEFITS].map((x) => [x.id || x.service_id || x.benefit_id, x]));
const homepageCategory = (id, cat) => {
  if (id === 'S-TRN-RIDE') return 'Transportation';
  if (id === 'S-PREV-WELLNESS') return 'Preventive';
  return ({ dental: 'Dental', eyecare: 'Vision', hearing: 'Hearing', diabetes: 'Diabetes supplies', nutrition: 'Nutrition',
    mobility: 'Medical equipment', dme: 'Medical equipment', braces: 'Medical equipment', respiratory: 'Medical equipment', sleep: 'Medical equipment',
    woundcare: 'Medical equipment', ostomy: 'Medical equipment', urology: 'Medical equipment', compression: 'Medical equipment',
    ssbci: 'Everyday extras' })[cat] || 'Pharmacy & OTC';
};
const toListing = (r) => {
  const item = catalog.get(r.target_id) || {};
  return {
    category: homepageCategory(r.target_id, item.category), benefit: item.product_name || item.service_name || item.benefit_name || r.target_id,
    status: r.coverage_status, value: r.member_cost, requirements: [r.benefit_pathway, r.requirements].filter(Boolean).join(' - '),
    url: r.official_source_url, evidence: `${r.official_source_name}, ${r.source_page}`,
  };
};
const homepagePlans = check.RI_OFFICIAL_SELECTOR_PLANS
  .filter((p) => p.state === 'RI' && /^(CMS:RI:|RIMCD:)/.test(String(p.id)))
  .map((p) => {
    const planRules = VERIFIED.rules.filter((r) => r.plan_id === p.id);
    return {
      id: p.id, name: p.official_plan_name, insurer: p.insurer_name, type: p.plan_type, card: String(p.id).startsWith('RIMCD:') ? 'medicaid' : 'medicare',
      listings: planRules.filter((r) => /^(covered|conditional)$/i.test(r.coverage_status)).map(toListing),
      notCovered: planRules.filter((r) => /not covered/i.test(r.coverage_status)).map(toListing),
    };
  })
  .sort((a, b) => (a.id.includes('ORIGINAL') ? -1 : b.id.includes('ORIGINAL') ? 1 : a.insurer.localeCompare(b.insurer) || a.name.localeCompare(b.name)));
fs.writeFileSync(VERIFIED_CARDS, JSON.stringify({ generated: VERIFIED.generated, state: 'RI', plans: homepagePlans }));
console.log(`Wrote ${path.relative(ROOT, VERIFIED_CARDS)} (${homepagePlans.length} Medicare/Medicaid plans, ${homepagePlans.filter((p) => p.listings.length).length} with verified listings)`);

console.log(`Quarantined ${quarantined.length} legacy RI rules; kept ${kept.length} non-RI rules; dropped ${data.COVERAGE_RULES.length - present.length} empty slots.`);
console.log(`Inserted ${VERIFIED.rules.length} verified rules, ${VERIFIED.benefits.length} benefits, ${VERIFIED.plans.length} plans.`);
console.log(`Wrote ${path.relative(ROOT, BUNDLE)}`);
