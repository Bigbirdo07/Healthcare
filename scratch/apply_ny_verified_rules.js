// Publish data/ny_verified_coverage_2026/NY_VERIFIED_RULES_2026.json to the
// marketplace. New York is the first state too large to inline (2,300+ plans,
// ~25k rules), so instead of a generated block of data like Rhode Island's it
// gets lazy-loaded files:
//
//   dist/marketplace/states/ny/plans.json        selector plans + new benefits,
//                                                fetched when NY is selected
//   dist/marketplace/states/ny/rules/<plan>.json one plan's rules, fetched
//                                                when that plan is selected
//   dist/ny_verified_cards.json                  homepage Medicare/Medicaid
//                                                cards (same shape as RI's)
//
// and a small generated loader in dist/marketplace/marketplace.js (between
// markers; re-running replaces it). dist/app.js is not touched.
//
// Usage: python3 scratch/build_ri_verified_rules.py data/ny_verified_coverage_2026/evidence_spec.json
//        node scratch/apply_ny_verified_rules.js

const fs = require('fs');
const path = require('path');
const loadBundle = require('./bundle_loader');

const ROOT = path.resolve(__dirname, '..');
const BUNDLE = path.join(ROOT, 'dist/marketplace/marketplace.js');
const OUT = path.join(ROOT, 'dist/marketplace/states/ny');
const VERIFIED = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/ny_verified_coverage_2026/NY_VERIFIED_RULES_2026.json'), 'utf8'));

const BLOCK_START = '  // --- LAZY STATE COVERAGE LOADER (GENERATED by scratch/apply_ny_verified_rules.js - do not edit) ---';
const BLOCK_END = '  // --- END LAZY STATE COVERAGE LOADER ---';

const ruleFile = (planId) => planId.replace(/[^A-Za-z0-9]+/g, '_') + '.json';

// 1. Validate against the marketplace catalog, as the RI apply step does.
const bundle = loadBundle(BUNDLE).__D;
const targetIds = new Set([
  ...bundle.PRODUCTS.map((p) => p.id),
  ...bundle.SERVICES.map((s) => s.id || s.service_id),
  ...bundle.BENEFITS.map((b) => b.id || b.benefit_id),
  ...VERIFIED.benefits.map((b) => b.id),
]);
const planIds = new Set(VERIFIED.plans.map((p) => p.id));
const problems = VERIFIED.rules.flatMap((r) => [
  ...(targetIds.has(r.target_id) ? [] : [`unknown target ${r.target_id} in ${r.rule_id}`]),
  ...(planIds.has(r.plan_id) ? [] : [`unknown plan ${r.plan_id} in ${r.rule_id}`]),
]);
const clash = VERIFIED.plans.filter((p) => bundle.getProductionSelectorPlans().some((q) => q.id === p.id));
if (problems.length || clash.length) {
  console.error('APPLY FAILED:\n  ' + [...new Set(problems), ...clash.map((p) => `plan ${p.id} already in the bundle`)].join('\n  '));
  process.exit(1);
}

// 2. Lazy files. A plan with no verified rule is labeled as under review, the
//    same way RI roster-only plans are.
const rulesByPlan = new Map();
VERIFIED.rules.forEach((r) => {
  if (!rulesByPlan.has(r.plan_id)) rulesByPlan.set(r.plan_id, []);
  rulesByPlan.get(r.plan_id).push(r);
});
const plans = VERIFIED.plans.map((p) => {
  const has = rulesByPlan.has(p.id);
  return {
    ...p,
    is_verified: has,
    roster_only: !has,
    benefits_under_review: !has,
    coverage_verification_status: p.coverage_verification_status || (has ? 'EXCERPT_MATCHED_IN_SOURCE_DOCUMENT' : 'VERIFICATION_PENDING'),
    rules_file: has ? ruleFile(p.id) : null,
  };
});
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'rules'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'plans.json'), JSON.stringify({ generated: VERIFIED.generated, state: 'NY', plans, benefits: VERIFIED.benefits }));
for (const [planId, rules] of rulesByPlan) fs.writeFileSync(path.join(OUT, 'rules', ruleFile(planId)), JSON.stringify(rules));

// 3. Loader in the bundle. Selection handlers wait for the state's plans and
//    the chosen plan's rules before rendering.
const block = `${BLOCK_START}
  // States whose plans and rules are fetched on demand (too large to inline).
  const LAZY_STATE_DATA = { NY: '/marketplace/states/ny/' };
  const lazyStateLoads = {};
  const lazyPlanLoads = {};

  function ensureStateData(state) {
    const base = LAZY_STATE_DATA[state];
    if (!base) return Promise.resolve();
    if (!lazyStateLoads[state]) {
      lazyStateLoads[state] = fetch(base + 'plans.json')
        .then((r) => (r.ok ? r.json() : Promise.reject(new Error('Could not load ' + state + ' plans'))))
        .then((d) => {
          RI_OFFICIAL_SELECTOR_PLANS.push(...d.plans);
          BENEFITS.push(...d.benefits.filter((b) => !BENEFITS.some((x) => x.id === b.id)));
        })
        .catch((err) => { delete lazyStateLoads[state]; console.error(err); });
    }
    return lazyStateLoads[state];
  }

  function ensurePlanRules(planId) {
    const plan = planId && RI_OFFICIAL_SELECTOR_PLANS.find((p) => p.id === planId);
    const base = plan && LAZY_STATE_DATA[plan.state];
    if (!base || !plan.rules_file) return Promise.resolve();
    if (!lazyPlanLoads[planId]) {
      lazyPlanLoads[planId] = fetch(base + 'rules/' + plan.rules_file)
        .then((r) => (r.ok ? r.json() : Promise.reject(new Error('Could not load rules for ' + planId))))
        .then((rules) => { COVERAGE_RULES.push(...rules); })
        .catch((err) => { delete lazyPlanLoads[planId]; console.error(err); });
    }
    return lazyPlanLoads[planId];
  }
${BLOCK_END}`;

let src = fs.readFileSync(BUNDLE, 'utf8');
const oldStart = src.indexOf(BLOCK_START);
if (oldStart !== -1) {
  const oldEnd = src.indexOf(BLOCK_END, oldStart) + BLOCK_END.length;
  src = src.slice(0, oldStart) + src.slice(oldEnd + 1);
}
const anchor = '  // --- END RI VERIFIED COVERAGE ---\n';
if (!src.includes(anchor)) throw new Error('RI verified coverage block not found');
src = src.replace(anchor, anchor + block + '\n');

// Hand-written selection code: each patch is applied once (skipped if present).
const patches = [
  ["const states = ['RI', 'MA', 'CT', 'NH', 'ME', 'VT'];", "const states = ['RI', 'MA', 'CT', 'NH', 'ME', 'VT', 'NY'];"],
  [
    "  function onStateChange(newState) {\n    activeState = newState;",
    "  function onStateChange(newState) {\n    if (LAZY_STATE_DATA[newState] && !lazyStateLoads[newState]) {\n      ensureStateData(newState).then(() => onStateChange(newState));\n      return;\n    }\n    activeState = newState;",
  ],
  [
    "  function onPlanChange(newPlanId) {\n    activePlanId = newPlanId;",
    "  function onPlanChange(newPlanId) {\n    if (newPlanId && !lazyPlanLoads[newPlanId] && RI_OFFICIAL_SELECTOR_PLANS.some((p) => p.id === newPlanId && p.rules_file)) {\n      ensurePlanRules(newPlanId).then(() => onPlanChange(newPlanId));\n      return;\n    }\n    activePlanId = newPlanId;",
  ],
  [
    "  function onInsurerChange(newInsurerId) {\n    selectedInsurerId = newInsurerId;\n    const res = window.getInsuranceSelectorOptions({\n      state: activeState,\n      cardType: activeCardType,\n      insurerId: selectedInsurerId\n    });\n    // Only pre-select when there is exactly one plan to choose from.\n    activePlanId = (res.plans && res.plans.length === 1) ? res.plans[0].id : null;\n",
    "  function onInsurerChange(newInsurerId) {\n    selectedInsurerId = newInsurerId;\n    const res = window.getInsuranceSelectorOptions({\n      state: activeState,\n      cardType: activeCardType,\n      insurerId: selectedInsurerId\n    });\n    // Only pre-select when there is exactly one plan to choose from.\n    activePlanId = (res.plans && res.plans.length === 1) ? res.plans[0].id : null;\n    if (activePlanId && !lazyPlanLoads[activePlanId] && RI_OFFICIAL_SELECTOR_PLANS.some((p) => p.id === activePlanId && p.rules_file)) {\n      ensurePlanRules(activePlanId).then(() => onInsurerChange(newInsurerId));\n      return;\n    }\n",
  ],
  [
    "  if (document.readyState === 'loading') {\n    document.addEventListener('DOMContentLoaded', init);\n  } else {\n    init();\n  }",
    "  // A homepage handoff into a lazy-loaded state needs its plans (and the\n  // linked plan's rules) before init reads the URL.\n  function bootMarketplace() {\n    const params = new URLSearchParams(window.location.search);\n    const lazyState = Object.keys(LAZY_STATE_DATA).find((s) => params.get('state') === s || String(params.get('plan_id') || '').includes(':' + s + ':') || String(params.get('plan_id') || '').startsWith(s + 'MCD:'));\n    if (!lazyState) return init();\n    ensureStateData(lazyState).then(() => ensurePlanRules(params.get('plan_id'))).then(init, init);\n  }\n\n  if (document.readyState === 'loading') {\n    document.addEventListener('DOMContentLoaded', bootMarketplace);\n  } else {\n    bootMarketplace();\n  }",
  ],
];
for (const [before, after] of patches) {
  if (src.includes(after)) continue;
  if (!src.includes(before)) throw new Error('marketplace.js patch anchor not found: ' + before.slice(0, 60));
  src = src.replace(before, after);
}

// The patched bundle must still evaluate and expose the loader.
fs.writeFileSync(BUNDLE + '.tmp', src);
try {
  const check = loadBundle(BUNDLE + '.tmp').__D;
  if (!check.COVERAGE_RULES.length) throw new Error('bundle evaluated without coverage rules');
} catch (err) {
  fs.rmSync(BUNDLE + '.tmp');
  console.error('APPLY FAILED: patched bundle does not evaluate: ' + err.message);
  process.exit(1);
}
fs.renameSync(BUNDLE + '.tmp', BUNDLE);

// 4. Homepage cards, built like RI's: every NY Medicare and Medicaid plan with
//    its evidence-backed listings.
const catalog = new Map([...bundle.PRODUCTS, ...bundle.SERVICES, ...bundle.BENEFITS, ...VERIFIED.benefits].map((x) => [x.id || x.service_id || x.benefit_id, x]));
const homepageCategory = (id, cat) => {
  if (id === 'S-TRN-RIDE') return 'Transportation';
  if (id === 'S-PREV-WELLNESS') return 'Preventive';
  return ({ dental: 'Dental', eyecare: 'Vision', hearing: 'Hearing', diabetes: 'Diabetes supplies', nutrition: 'Nutrition',
    mobility: 'Medical equipment', dme: 'Medical equipment', braces: 'Medical equipment', respiratory: 'Medical equipment', sleep: 'Medical equipment',
    woundcare: 'Medical equipment', ostomy: 'Medical equipment', urology: 'Medical equipment', compression: 'Medical equipment',
    ssbci: 'Everyday extras' })[cat] || 'Pharmacy & OTC';
};
const toListing = (r) => {
  const item = catalog.get(r.target_id) || {};
  return {
    category: homepageCategory(r.target_id, item.category), benefit: item.product_name || item.service_name || item.benefit_name || r.target_id,
    status: r.coverage_status, value: r.member_cost, requirements: [r.benefit_pathway, r.requirements].filter(Boolean).join(' - '),
    url: r.official_source_url, evidence: `${r.official_source_name}, ${r.source_page}`,
  };
};
const homepagePlans = plans
  .filter((p) => /^(CMS:NY:|NYMCD:)/.test(p.id))
  .map((p) => {
    const planRules = rulesByPlan.get(p.id) || [];
    return {
      id: p.id, name: p.official_plan_name, insurer: p.insurer_name, type: p.plan_type, card: p.id.startsWith('NYMCD:') ? 'medicaid' : 'medicare',
      listings: planRules.filter((r) => /^(covered|conditional)$/i.test(r.coverage_status)).map(toListing),
      notCovered: planRules.filter((r) => /not covered/i.test(r.coverage_status)).map(toListing),
    };
  })
  .sort((a, b) => (a.id.includes('ORIGINAL') ? -1 : b.id.includes('ORIGINAL') ? 1 : a.insurer.localeCompare(b.insurer) || a.name.localeCompare(b.name)));
fs.writeFileSync(path.join(ROOT, 'dist/ny_verified_cards.json'), JSON.stringify({ generated: VERIFIED.generated, state: 'NY', plans: homepagePlans }));

const size = (f) => (fs.statSync(f).size / 1e6).toFixed(1) + ' MB';
console.log(`Wrote dist/marketplace/states/ny/plans.json (${plans.length} plans, ${size(path.join(OUT, 'plans.json'))}) and ${rulesByPlan.size} rule files (${VERIFIED.rules.length} rules)`);
console.log(`Wrote dist/ny_verified_cards.json (${homepagePlans.length} Medicare/Medicaid plans, ${homepagePlans.filter((p) => p.listings.length).length} with verified listings)`);
console.log(`Patched ${path.relative(ROOT, BUNDLE)} (lazy loader + NY selection)`);
